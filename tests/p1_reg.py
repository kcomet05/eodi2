import pathlib
from playwright.sync_api import sync_playwright
html=pathlib.Path(str(pathlib.Path(__file__).parent.parent/'index.html')).read_text(encoding='utf8')
mock=pathlib.Path(str(pathlib.Path(__file__).parent/'mock.js')).read_text(encoding='utf8')
ok=lambda c,m:print(('PASS ' if c else 'FAIL ')+m)
with sync_playwright() as p:
    b=p.chromium.launch(args=["--no-sandbox"]); pg=b.new_page(viewport={"width":390,"height":844})
    errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.add_init_script("localStorage.setItem('dc_couple',JSON.stringify({names:['지우','하준'],me:0,since:'2025-03-01',code:'',dirty:false}));window.__LAB={scenario:'normal'};")
    pg.add_init_script(mock)
    pg.route("**/*",lambda r: r.fulfill(status=200,content_type='text/html',body=html) if r.request.url=='http://t.local/' else r.abort())
    pg.goto("http://t.local/"); pg.wait_for_timeout(500)
    ok(pg.is_visible('#home'),'seeded profile skips onboarding')
    # plan: search + add
    pg.click('#home [data-go="plan"]'); pg.wait_for_timeout(300)
    pg.click('#q'); pg.keyboard.type('성수 카페'); pg.wait_for_timeout(900)
    n=pg.locator('.sgi').count(); ok(n>=2,'search returns results: %d'%n)
    pg.click('.sgi >> nth=0'); pg.wait_for_timeout(900)
    pg.click('#q'); pg.keyboard.type('성수 카페'); pg.wait_for_timeout(900); pg.click('.sgi >> nth=1'); pg.wait_for_timeout(1200)
    ok(pg.locator('#stopList .stop').count()==2,'two stops added')
    t0=pg.eval_on_selector_all('#stopList .stop small','e=>e.map(x=>x.textContent)')
    pg.select_option('#stopList .stsel >> nth=0','120'); pg.wait_for_timeout(300)
    t1=pg.eval_on_selector_all('#stopList .stop small','e=>e.map(x=>x.textContent)'); ok(t0!=t1,'stay change recalculates times')
    ok(pg.is_visible('#nearby') and pg.locator('#nearby .nbi').count()>0,'nearby suggestions shown')
    pg.screenshot(path='/tmp/p1_reg_plan.png',full_page=True)
    ok('마무리' in pg.inner_text('#walkTotal'),'travel total: '+pg.inner_text('#walkTotal'))
    pg.click('#plan [data-go=home]')
    # rec
    pg.click('#home [data-go=rec]'); pg.wait_for_timeout(1000)
    ok(pg.locator('#recCard li').count()>=2,'recommendation card has stops')
    pg.click('[data-area="한남동"]'); pg.wait_for_timeout(700); ok('한남동' in pg.inner_text('#recCard'),'area choice applied')
    pg.screenshot(path='/tmp/p1_reg_rec.png',full_page=True)
    pg.click('#useCourse'); pg.wait_for_timeout(5000); print('plan vis',pg.is_visible('#plan'),'stops',pg.locator('#stopList .stop').count(),'recCard stops',pg.locator('#recCard li').count()); ok(pg.is_visible('#plan') and pg.locator('#stopList .stop').count()>=2,'use course -> planner with stops')
    pg.screenshot(path='/tmp/p1_reg_plan2.png',full_page=True)
    ok(not errs,'no page errors '+str(errs)); b.close()
